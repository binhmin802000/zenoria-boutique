-- ============================================================
-- LOT 2a (SQL) : STOCK DES BIJOUX NORMAUX — reservations, additif uniquement.
-- Objectif : meme principe que les pieces uniques (product_holds), mais avec des QUANTITES :
--   disponible = products.stock - somme(reservations actives/consommees non expirees)
-- Le stock n'est JAMAIS decremente a la reservation, seulement a la consommation (paiement confirme),
-- conformement a la decision validee « stock decremente automatiquement au paiement ».
--
-- Nouveaux objets, TOUS additifs (aucune fonction existante modifiee, aucun comportement du site change) :
--   - table stock_holds (reservations de stock, par quantite)
--   - hold_order_stock_internal(order_id, expires_at)   -> reserve, fermee a tous les roles (comme hold_order_pieces_internal)
--   - release_order_stock(order_id, reason)             -> libere, fermee a tous les roles (comme release_order_pieces)
--   - consume_order_stock(order_id)                     -> decremente products.stock, fermee a tous les roles
--   - consume_order_items(order_id)                     -> orchestre consume_order_pieces (existante) + consume_order_stock
--   - release_order_items(order_id, reason)              -> orchestre release_order_pieces (existante) + release_order_stock
--   - admin_relist_order(order_id)                       -> remet en vente pieces ET stock d'une commande REMBOURSEE
--   - public_stock_states()                              -> lecture publique (stock, reserve, disponible) par produit
--
-- « Paiement recu sans stock disponible » (decision validee) : consume_order_stock NE BLOQUE JAMAIS le paiement ;
--   si le stock est devenu insuffisant entre-temps, il decremente quand meme (peut aller en negatif) et renvoie
--   une alerte dans sa reponse ; cette alerte sera ecrite en ADMIN UNIQUEMENT (customer_visible = false) par la
--   fonction appelante (admin_confirm_transfer / webhook), qui sera modifiee au lot 2a-bis.
--
-- Portee de ce lot : PUREMENT ADDITIF. Rien n'appelle encore ces fonctions (create_transfer_order, create_card_order,
--   admin_confirm_transfer, le webhook Stripe les appelleront au lot 2a-bis / 2b). Aucun effet visible sur le site.
--   Peut etre applique en production des maintenant, base unique ou non.
--
-- Chaque instruction DDL est executee via EXECUTE (avec un marqueur dedie) pour eviter toute ambiguite de parsing
-- avec le corps des fonctions creees (qui utilisent leur propre marqueur).
-- Tout ou rien. Retour arriere : lot2a_rollback.sql
-- ============================================================
do $zen$
begin
  if to_regclass('public.stock_holds') is not null then
    raise exception 'ABANDON : le lot 2a est deja applique (table stock_holds presente) ; rien n''a ete modifie';
  end if;

  -- 1. Table des reservations de stock
  execute $ddl$
    create table public.stock_holds (
      id bigint generated by default as identity primary key,
      product_id bigint not null references public.products(id),
      order_id bigint not null references public.orders(id) on delete cascade,
      qty integer not null check (qty > 0),
      status text not null check (status in ('active', 'consumed', 'released')),
      expires_at timestamptz,
      created_at timestamptz not null default now(),
      released_at timestamptz,
      release_reason text
    )
  $ddl$;
  execute $ddl$ create index stock_holds_product_idx on public.stock_holds (product_id, status) $ddl$;
  execute $ddl$ create index stock_holds_order_idx on public.stock_holds (order_id) $ddl$;
  execute $ddl$ comment on table public.stock_holds is 'Reservations de stock des bijoux normaux (is_unique = false), par quantite. Decompte reel uniquement a la consommation (paiement confirme).' $ddl$;
  execute $ddl$ alter table public.stock_holds enable row level security $ddl$;
  execute $ddl$ create policy stock_holds_admin_read on public.stock_holds for select using (public.is_admin()) $ddl$;

  -- 2. Reservation (additionne les lignes order_items par produit non unique, verifie la disponibilite)
  execute $ddl$
  create function public.hold_order_stock_internal(p_order_id bigint, p_expires_at timestamp with time zone)
   returns integer
   language plpgsql
   security definer
   set search_path to 'public'
  as $function$
  declare
    r record;
    v_conflicts bigint[] := '{}';
    v_count integer := 0;
    v_held numeric;
    v_available numeric;
  begin
    for r in
      select oi.product_id, sum(oi.qty) as qty, p.stock
        from public.order_items oi
        join public.products p on p.id = oi.product_id
       where oi.order_id = p_order_id and p.is_unique is not true
       group by oi.product_id, p.stock
       order by oi.product_id
    loop
      if exists (
        select 1 from public.stock_holds h
         where h.product_id = r.product_id and h.order_id = p_order_id and h.status in ('active', 'consumed')
      ) then
        v_count := v_count + 1;
        continue;
      end if;

      update public.stock_holds
         set status = 'released', released_at = now(), release_reason = 'expired'
       where product_id = r.product_id
         and status = 'active'
         and expires_at is not null
         and expires_at <= now();

      select coalesce(sum(qty), 0) into v_held
        from public.stock_holds
       where product_id = r.product_id and status in ('active', 'consumed');

      v_available := r.stock - v_held;
      if r.qty > v_available then
        v_conflicts := v_conflicts || r.product_id;
        continue;
      end if;

      insert into public.stock_holds (product_id, order_id, qty, status, expires_at)
      values (r.product_id, p_order_id, r.qty, 'active', p_expires_at);
      v_count := v_count + 1;
    end loop;

    if coalesce(array_length(v_conflicts, 1), 0) > 0 then
      raise exception 'STOCK_UNAVAILABLE:%', array_to_string(v_conflicts, ',');
    end if;

    return v_count;
  end
  $function$
  $ddl$;

  -- 3. Liberation (annulation/expiration)
  execute $ddl$
  create function public.release_order_stock(p_order_id bigint, p_reason text)
   returns integer
   language plpgsql
   security definer
   set search_path to 'public'
  as $function$
  declare
    v_n integer;
  begin
    if p_reason is null or p_reason not in ('customer_cancelled', 'admin_cancelled', 'expired', 'payment_failed', 'admin_relisted') then
      raise exception 'INVALID_REASON';
    end if;
    update public.stock_holds
       set status = 'released', released_at = now(), release_reason = p_reason
     where order_id = p_order_id and status = 'active';
    get diagnostics v_n = row_count;
    return v_n;
  end
  $function$
  $ddl$;

  -- 4. Consommation (paiement confirme) : decremente products.stock, ne bloque jamais le paiement
  execute $ddl$
  create function public.consume_order_stock(p_order_id bigint)
   returns jsonb
   language plpgsql
   security definer
   set search_path to 'public'
  as $function$
  declare
    r record;
    v_done integer := 0;
    v_alerts jsonb := '[]'::jsonb;
    v_current_stock integer;
  begin
    for r in
      select h.id, h.product_id, h.qty
        from public.stock_holds h
       where h.order_id = p_order_id and h.status = 'active'
       order by h.id
    loop
      if exists (
        select 1 from public.stock_holds h2
         where h2.product_id = r.product_id and h2.order_id = p_order_id and h2.id <> r.id and h2.status = 'consumed'
      ) then
        continue;
      end if;

      update public.stock_holds set status = 'consumed' where id = r.id;

      select stock into v_current_stock from public.products where id = r.product_id for update;
      if v_current_stock < r.qty then
        v_alerts := v_alerts || jsonb_build_object('product_id', r.product_id, 'stock_avant', v_current_stock, 'quantite_requise', r.qty);
      end if;
      update public.products set stock = stock - r.qty where id = r.product_id;
      v_done := v_done + 1;
    end loop;

    return jsonb_build_object('consumed', v_done, 'alerts', v_alerts);
  end
  $function$
  $ddl$;

  -- 5. Orchestrateurs pieces + stock (utilises par le futur 2a-bis / 2b, sans rien changer aujourd'hui)
  execute $ddl$
  create function public.consume_order_items(p_order_id bigint)
   returns jsonb
   language plpgsql
   security definer
   set search_path to ''
  as $function$
  declare
    v_pieces jsonb;
    v_stock jsonb;
  begin
    v_pieces := public.consume_order_pieces(p_order_id);
    if jsonb_array_length(v_pieces -> 'conflicts') > 0 then
      raise exception 'PIECE_CONFLICT:%', (v_pieces -> 'conflicts')::text;
    end if;
    v_stock := public.consume_order_stock(p_order_id);
    return jsonb_build_object('pieces', v_pieces, 'stock', v_stock);
  end
  $function$
  $ddl$;

  execute $ddl$
  create function public.release_order_items(p_order_id bigint, p_reason text)
   returns jsonb
   language plpgsql
   security definer
   set search_path to ''
  as $function$
  declare
    v_pieces integer;
    v_stock integer;
  begin
    v_pieces := public.release_order_pieces(p_order_id, p_reason);
    v_stock := public.release_order_stock(p_order_id, p_reason);
    return jsonb_build_object('pieces_released', v_pieces, 'stock_released', v_stock);
  end
  $function$
  $ddl$;

  -- 6. Remise en vente apres remboursement (option B validee) : pieces ET stock, un seul appel, un seul journal
  execute $ddl$
  create function public.admin_relist_order(p_order_id bigint)
   returns jsonb
   language plpgsql
   security definer
   set search_path to ''
  as $function$
  declare
    v_status text;
    v_pieces integer := 0;
    v_stock_rows integer := 0;
    v_stock_qty integer := 0;
    r record;
  begin
    if not public.is_admin() then raise exception 'FORBIDDEN'; end if;

    select status into v_status from public.orders where id = p_order_id for update;
    if not found then raise exception 'ORDER_NOT_FOUND'; end if;
    if v_status <> 'refunded' then raise exception 'ORDER_STATE'; end if;

    update public.product_holds
       set status = 'released', released_at = now(), release_reason = 'admin_relisted'
     where order_id = p_order_id and status = 'consumed';
    get diagnostics v_pieces = row_count;

    for r in
      select id, product_id, qty from public.stock_holds
       where order_id = p_order_id and status = 'consumed'
    loop
      update public.stock_holds set status = 'released', released_at = now(), release_reason = 'admin_relisted' where id = r.id;
      update public.products set stock = stock + r.qty where id = r.product_id;
      v_stock_rows := v_stock_rows + 1;
      v_stock_qty := v_stock_qty + r.qty;
    end loop;

    if v_pieces = 0 and v_stock_rows = 0 then
      raise exception 'NOTHING_TO_RELIST';
    end if;

    insert into public.order_status_history (order_id, status, note, actor_email)
    values (
      p_order_id, 'refunded',
      'Pièce(s) remise(s) en vente : ' || v_pieces || '. Stock remis en vente : ' || v_stock_qty || ' exemplaire(s) sur ' || v_stock_rows || ' ligne(s).',
      public.current_actor_email()
    );

    return jsonb_build_object('order_id', p_order_id, 'pieces_relisted', v_pieces, 'stock_rows_relisted', v_stock_rows, 'stock_qty_relisted', v_stock_qty);
  end
  $function$
  $ddl$;

  -- 7. Lecture publique de la disponibilite (en miroir de public_piece_states)
  execute $ddl$
  create function public.public_stock_states()
   returns table(product_id bigint, stock integer, reserved integer, available integer)
   language sql
   stable
   security definer
   set search_path to 'public'
  as $function$
    select p.id,
           p.stock,
           coalesce((
             select sum(h.qty)::integer from public.stock_holds h
              where h.product_id = p.id and h.status in ('active', 'consumed')
                and (h.status = 'consumed' or h.expires_at is null or h.expires_at > now())
           ), 0) as reserved,
           greatest(0, p.stock - coalesce((
             select sum(h.qty)::integer from public.stock_holds h
              where h.product_id = p.id and h.status in ('active', 'consumed')
                and (h.status = 'consumed' or h.expires_at is null or h.expires_at > now())
           ), 0)) as available
      from public.products p
     where p.active and p.is_unique is not true
  $function$
  $ddl$;

  -- 8. Droits : fonctions internes fermees a tous ; admin_relist_order reservee aux comptes connectes (verifie is_admin() en interne) ;
  --    public_stock_states lisible par tout le monde (comme public_piece_states)
  execute $ddl$ revoke all on function public.hold_order_stock_internal(bigint, timestamp with time zone) from public, anon, authenticated $ddl$;
  execute $ddl$ revoke all on function public.release_order_stock(bigint, text) from public, anon, authenticated $ddl$;
  execute $ddl$ revoke all on function public.consume_order_stock(bigint) from public, anon, authenticated $ddl$;
  execute $ddl$ revoke all on function public.consume_order_items(bigint) from public, anon, authenticated $ddl$;
  execute $ddl$ revoke all on function public.release_order_items(bigint, text) from public, anon, authenticated $ddl$;

  execute $ddl$ revoke all on function public.admin_relist_order(bigint) from public, anon $ddl$;
  execute $ddl$ grant execute on function public.admin_relist_order(bigint) to authenticated $ddl$;

  execute $ddl$ revoke all on function public.public_stock_states() from public $ddl$;
  execute $ddl$ grant execute on function public.public_stock_states() to anon, authenticated $ddl$;
end $zen$;

-- Verification (lecture seule) : attendu = toutes les internes a false/false ; admin_relist_order false/true ; public_stock_states true/true
select p.oid::regprocedure::text as fonction,
       has_function_privilege('anon', p.oid, 'EXECUTE') as anon,
       has_function_privilege('authenticated', p.oid, 'EXECUTE') as authenticated
  from pg_proc p
 where p.pronamespace = 'public'::regnamespace
   and p.proname in ('hold_order_stock_internal', 'release_order_stock', 'consume_order_stock',
                      'consume_order_items', 'release_order_items', 'admin_relist_order', 'public_stock_states')
 order by 1;
